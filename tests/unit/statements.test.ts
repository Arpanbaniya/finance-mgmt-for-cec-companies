import { randomUUID } from "node:crypto";
import { expect, it } from "vitest";
import { AccountMovement, calculateStatements, ReportInstant, StatementInterval, type AccountMovementValue } from "@/domain/statements";

function row(code: string, type: AccountMovementValue["type"], debit: string, credit: string): AccountMovementValue {
  return { accountId: randomUUID(), accountVersion: 1, code, name: code, type, normalSide: type === "asset" || type === "expense" ? "debit" : "credit",
    statementSection: type === "asset" ? "assets" : type === "liability" ? "liabilities" : type === "equity" ? "equity" : type === "revenue" ? "revenue" : "expenses",
    openingDebit: "0.00", openingCredit: "0.00", periodDebit: debit, periodCredit: credit, yearDebit: debit, yearCredit: credit };
}
// Independently retained expected amounts, not generated by report functions.
const fixture = () => [row("BANK", "asset", "98500.00", "0.00"), row("AR", "asset", "15300.00", "0.00"), row("WITHHOLDING", "asset", "1000.00", "0.00"),
  row("WAGES", "expense", "22000.00", "0.00"), row("EMPLOYER", "expense", "700.00", "0.00"), row("CAPITAL", "equity", "0.00", "100000.00"),
  row("REVENUE", "revenue", "0.00", "33000.00"), row("OUTPUT-TAX", "liability", "0.00", "3300.00"), row("STATUTORY", "liability", "0.00", "1200.00")];
it("ties the independent nine-account fixture without putting output tax in revenue", () => {
  const report = calculateStatements(fixture());
  expect(report.trialBalance.totals).toEqual({ opening: { debit: "0.00", credit: "0.00" }, movement: { debit: "137500.00", credit: "137500.00" }, closing: { debit: "137500.00", credit: "137500.00" } });
  expect(report.incomeMovement).toEqual({ revenue: "33000.00", expenses: "22700.00", result: "10300.00" });
  expect(report.balanceSheet).toEqual({ assets: "114800.00", liabilities: "4500.00", postedEquity: "100000.00", currentYearResult: "10300.00", priorUnclosedResult: "0.00", equity: "110300.00", difference: "0.00" });
});
it("rolls opening balances and period movements into closing, not into period income", () => {
  const rows = fixture().map(value => ({ ...value, openingDebit: value.periodDebit, openingCredit: value.periodCredit, periodDebit: "0.00", periodCredit: "0.00", yearDebit: "0.00", yearCredit: "0.00" }));
  const report = calculateStatements(rows);
  expect(report.trialBalance.totals.opening).toEqual({ debit: "137500.00", credit: "137500.00" });
  expect(report.incomeMovement.result).toBe("0.00");
  expect(report.balanceSheet).toMatchObject({ currentYearResult: "0.00", priorUnclosedResult: "10300.00", equity: "110300.00" });
});
it("nets one account across historical versions before splitting debit and credit", () => {
  const asset = row("ASSET", "asset", "1.00", "0.00"), equity = row("EQUITY", "equity", "0.00", "1.00");
  const report = calculateStatements([asset, equity,
    { ...asset, accountVersion: 2, name: "Renamed asset", periodDebit: "0.00", periodCredit: "1.00", yearDebit: "0.00", yearCredit: "1.00" },
    { ...equity, accountVersion: 2, periodDebit: "1.00", periodCredit: "0.00", yearDebit: "1.00", yearCredit: "0.00" }]);
  expect(report.trialBalance.rows).toHaveLength(2);
  expect(report.trialBalance.rows[0]).toMatchObject({ name: "Renamed asset", accountVersions: [1, 2], closing: { debit: "0.00", credit: "0.00" } });
  expect(report.trialBalance.totals.closing).toEqual({ debit: "0.00", credit: "0.00" });
});
it("counts an explicit transfer to equity once rather than adding gross revenue again", () => {
  const rows = [row("ASSET", "asset", "10.00", "0.00"), row("REVENUE", "revenue", "10.00", "10.00"), row("EQUITY", "equity", "0.00", "10.00")];
  expect(calculateStatements(rows).balanceSheet).toMatchObject({ assets: "10.00", postedEquity: "10.00", currentYearResult: "0.00", equity: "10.00" });
  // This arithmetic witness does not certify the future year-close source.
});
it("presents losses and contra balances with their real signs regardless of normal side", () => {
  const asset = row("ASSET", "asset", "0.00", "0.01"), expense = row("EXPENSE", "expense", "0.01", "0.00");
  expect(calculateStatements([asset, expense]).balanceSheet).toMatchObject({ assets: "-0.01", currentYearResult: "-0.01", equity: "-0.01", difference: "0.00" });
});
it("fails closed for a one-paisa imbalance, duplicate aggregates and inconsistent history", () => {
  const rows = fixture();
  expect(() => calculateStatements([{ ...rows[0], periodDebit: "98500.01" }, ...rows.slice(1)])).toThrow("balance exactly");
  expect(() => calculateStatements([...rows, rows[0]])).toThrow("distinct retained");
  expect(() => calculateStatements([...rows, { ...rows[0], accountVersion: 2, code: "DIFFERENT" }])).toThrow("classification");
});
it("rejects numeric money, exponent notation, extra precision and conflicting retained mapping", () => {
  const value = fixture()[0];
  for (const bad of [1, "1e2", "1.001", "NaN", "Infinity", "-1.00", "1000000000000000000.00"]) expect(AccountMovement.safeParse({ ...value, periodDebit: bad }).success).toBe(false);
  expect(AccountMovement.safeParse({ ...value, statementSection: "revenue" }).success).toBe(false);
  expect(AccountMovement.safeParse({ ...value, privateWorkerName: "Not a report field" }).success).toBe(false);
});
it("retains a paise above Number's safe range and rejects overflowing report totals", () => {
  const amount = "9007199254740992.01";
  expect(calculateStatements([row("ASSET", "asset", amount, "0.00"), row("EQUITY", "equity", "0.00", amount)]).balanceSheet.assets).toBe(amount);
  const maximum = "999999999999999999.99";
  expect(() => calculateStatements([row("A", "asset", maximum, "0.00"), row("B", "asset", maximum, "0.00"), row("E", "equity", "0.00", maximum), row("F", "equity", "0.00", maximum)])).toThrow("supported range");
});
it("requires explicit valid exclusive dates and exact normalized knowledge instants", () => {
  expect(StatementInterval.safeParse({ fromDate: "2026-01-01", toDateExclusive: "2027-01-01", knownAt: "2026-10-11T01:00:00.123456Z" }).success).toBe(true);
  for (const value of ["2026-02-30T01:00:00.000000Z", "2026-10-11T01:00:00.123Z", "2026-10-11T01:00:00.123456+00:00", "2026-10-11T25:00:00.123456Z"]) expect(ReportInstant.safeParse(value).success).toBe(false);
  expect(StatementInterval.safeParse({ fromDate: "2026-01-01", toDateExclusive: "2026-01-01" }).success).toBe(false);
  expect(StatementInterval.safeParse({ fromDate: "2026-01-01", toDateExclusive: "2027-01-01", dimensions: { workerId: randomUUID() } }).success).toBe(false);
});
it("keeps an empty ledger visibly empty with exact zero totals", () => {
  const report = calculateStatements([]); expect(report.trialBalance.rows).toEqual([]);
  expect(report.balanceSheet).toMatchObject({ assets: "0.00", liabilities: "0.00", equity: "0.00", difference: "0.00" });
});
